export function isIdActuallyAvailable(civName: string, id: string | number, jsonAvailable: boolean): boolean {
    const civ = civName.charAt(0).toUpperCase() + civName.slice(1).toLowerCase();
    const override = CIV_OVERRIDES[civ];
    if (!override) return jsonAvailable;
    const sId = id.toString().replace('b_', '');
    if (override.forceEnable?.some(e => e.toString() === sId)) return true;
    if (override.forceDisable?.some(d => d.toString() === sId)) return false;
    return jsonAvailable;
}
